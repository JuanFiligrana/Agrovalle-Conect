CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    cedula VARCHAR(50) NOT NULL,
    municipio VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    contrasena_hash VARCHAR(100) NOT NULL,
    CONSTRAINT uk_usuarios_correo UNIQUE (correo),
    CONSTRAINT uk_usuarios_cedula UNIQUE (cedula),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('AGRICULTOR', 'COMPRADOR'))
);

CREATE TABLE IF NOT EXISTS fincas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agricultor_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    municipio VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    CONSTRAINT fk_fincas_agricultor
        FOREIGN KEY (agricultor_id) REFERENCES usuarios(id)
);

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    CONSTRAINT uk_productos_categoria_nombre UNIQUE (categoria_id, nombre),
    CONSTRAINT fk_productos_categoria
        FOREIGN KEY (categoria_id) REFERENCES categorias(id)
);

CREATE TABLE IF NOT EXISTS cosechas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finca_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    cantidad_kg NUMERIC(14, 3) NOT NULL,
    precio_cop_kg NUMERIC(14, 2) NOT NULL,
    fecha_cosecha DATE NOT NULL,
    activa BOOLEAN NOT NULL,
    CONSTRAINT ck_cosechas_cantidad CHECK (cantidad_kg > 0),
    CONSTRAINT ck_cosechas_precio CHECK (precio_cop_kg > 0),
    CONSTRAINT fk_cosechas_finca FOREIGN KEY (finca_id) REFERENCES fincas(id),
    CONSTRAINT fk_cosechas_producto FOREIGN KEY (producto_id) REFERENCES productos(id)
);

CREATE TABLE IF NOT EXISTS interacciones_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprador_id BIGINT NOT NULL REFERENCES usuarios(id),
    cosecha_id BIGINT NOT NULL REFERENCES cosechas(id),
    mensaje VARCHAR(1000) NOT NULL,
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_contacto_mensaje CHECK (CHAR_LENGTH(TRIM(mensaje)) BETWEEN 1 AND 1000)
);

CREATE TABLE IF NOT EXISTS notificaciones_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contacto_id BIGINT NOT NULL UNIQUE REFERENCES interacciones_contacto(id),
    destinatario_id BIGINT NOT NULL REFERENCES usuarios(id),
    leida BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS ix_contacto_comprador ON interacciones_contacto(comprador_id);
CREATE INDEX IF NOT EXISTS ix_notificacion_destinatario
    ON notificaciones_contacto(destinatario_id, id);

-- Evolución compatible: no elimina usuarios, publicaciones ni contactos existentes.
ALTER TABLE usuarios DROP CONSTRAINT IF EXISTS ck_usuarios_rol;
ALTER TABLE usuarios ADD CONSTRAINT ck_usuarios_rol
    CHECK (rol IN ('AGRICULTOR', 'COMPRADOR', 'ADMINISTRADOR'));
ALTER TABLE cosechas DROP CONSTRAINT IF EXISTS ck_cosechas_cantidad;
ALTER TABLE cosechas ADD CONSTRAINT ck_cosechas_cantidad CHECK (cantidad_kg >= 0);

CREATE TABLE IF NOT EXISTS carritos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprador_id BIGINT NOT NULL REFERENCES usuarios(id),
    abierto BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrito_id BIGINT NOT NULL REFERENCES carritos(id),
    cosecha_id BIGINT NOT NULL REFERENCES cosechas(id),
    cantidad_kg NUMERIC(14, 3) NOT NULL CHECK (cantidad_kg > 0),
    precio_cop_kg NUMERIC(14, 2) NOT NULL CHECK (precio_cop_kg > 0),
    vence_en TIMESTAMP WITH TIME ZONE NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_reserva_carrito_oferta UNIQUE (carrito_id, cosecha_id)
);

CREATE TABLE IF NOT EXISTS pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comprador_id BIGINT NOT NULL REFERENCES usuarios(id),
    agricultor_id BIGINT NOT NULL REFERENCES usuarios(id),
    carrito_id BIGINT NOT NULL UNIQUE REFERENCES carritos(id),
    clave VARCHAR(128) NOT NULL,
    estado VARCHAR(30) NOT NULL CHECK (estado IN
        ('PENDIENTE', 'LISTO_PARA_DESPACHO', 'EN_CAMINO', 'ENTREGADO', 'CANCELADA')),
    total NUMERIC(30, 2) NOT NULL CHECK (total > 0),
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_programada TIMESTAMP WITH TIME ZONE,
    ruta VARCHAR(500),
    CONSTRAINT uk_pedido_idempotencia UNIQUE (comprador_id, clave)
);

CREATE TABLE IF NOT EXISTS pedido_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    cosecha_id BIGINT NOT NULL REFERENCES cosechas(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    producto VARCHAR(100) NOT NULL,
    cantidad_kg NUMERIC(14, 3) NOT NULL CHECK (cantidad_kg > 0),
    precio_cop_kg NUMERIC(14, 2) NOT NULL CHECK (precio_cop_kg > 0),
    CONSTRAINT uk_linea_pedido_oferta UNIQUE (pedido_id, cosecha_id)
);

CREATE TABLE IF NOT EXISTS eventos_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    estado VARCHAR(30) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    descripcion VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS avisos_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    destinatario_id BIGINT NOT NULL REFERENCES usuarios(id),
    mensaje VARCHAR(500) NOT NULL,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS transacciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_item_id BIGINT UNIQUE REFERENCES pedido_items(id),
    producto_id BIGINT NOT NULL REFERENCES productos(id),
    producto VARCHAR(100) NOT NULL,
    precio_cop_kg NUMERIC(14, 2) NOT NULL CHECK (precio_cop_kg > 0),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PENDIENTE', 'COMPLETADA', 'CANCELADA')),
    finalizada_en TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS ix_carritos_comprador ON carritos(comprador_id, abierto);
CREATE INDEX IF NOT EXISTS ix_reservas_vigentes ON reservas(cosecha_id, activa, vence_en);
CREATE INDEX IF NOT EXISTS ix_pedidos_comprador ON pedidos(comprador_id, id);
CREATE INDEX IF NOT EXISTS ix_pedidos_agricultor ON pedidos(agricultor_id, id);
CREATE INDEX IF NOT EXISTS ix_eventos_pedido ON eventos_pedido(pedido_id, fecha, id);
CREATE INDEX IF NOT EXISTS ix_avisos_destinatario ON avisos_pedido(destinatario_id, fecha, id);
CREATE INDEX IF NOT EXISTS ix_transacciones_fecha ON transacciones(estado, finalizada_en);
