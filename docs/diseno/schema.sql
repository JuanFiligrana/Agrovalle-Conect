CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    cedula VARCHAR(50) NOT NULL,
    municipio VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    contrasena_hash VARCHAR(100) NOT NULL,
    CONSTRAINT uk_usuarios_correo UNIQUE (correo),
    CONSTRAINT uk_usuarios_cedula UNIQUE (cedula),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('AGRICULTOR', 'COMPRADOR'))
);

CREATE TABLE IF NOT EXISTS fincas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agricultor_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    municipio VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    CONSTRAINT fk_fincas_agricultor
        FOREIGN KEY (agricultor_id) REFERENCES usuarios(id)
);

CREATE TABLE IF NOT EXISTS categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT uk_categorias_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    CONSTRAINT uk_productos_categoria_nombre UNIQUE (categoria_id, nombre),
    CONSTRAINT fk_productos_categoria
        FOREIGN KEY (categoria_id) REFERENCES categorias(id)
);

CREATE TABLE IF NOT EXISTS cosechas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finca_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    cantidad_kg NUMERIC(14, 3) NOT NULL,
    precio_cop_kg NUMERIC(14, 2) NOT NULL,
    fecha_cosecha DATE NOT NULL,
    activa BOOLEAN NOT NULL,
    CONSTRAINT ck_cosechas_cantidad CHECK (cantidad_kg > 0),
    CONSTRAINT ck_cosechas_precio CHECK (precio_cop_kg > 0),
    CONSTRAINT fk_cosechas_finca FOREIGN KEY (finca_id) REFERENCES fincas(id),
    CONSTRAINT fk_cosechas_producto FOREIGN KEY (producto_id) REFERENCES productos(id)
);
