CREATE VIEW agrovalle.v_disponibilidad AS
SELECT c.id_cosecha,
       c.cantidad_fisica_kg - COALESCE((
           SELECT SUM(r.cantidad_kg)
           FROM agrovalle.reserva r
           WHERE r.id_cosecha = c.id_cosecha
             AND r.estado = 'ACTIVA'
             AND r.vence_en > CURRENT_TIMESTAMP
       ), 0) AS cantidad_disponible_kg
FROM agrovalle.cosecha c;

CREATE VIEW agrovalle.v_total_pedido AS
SELECT p.id_pedido,
       COALESCE(SUM(ROUND(d.cantidad_kg * d.precio_unitario_cop_kg, 2)), 0) AS total_cop
FROM agrovalle.pedido p
LEFT JOIN agrovalle.detalle_pedido d ON d.id_pedido = p.id_pedido
GROUP BY p.id_pedido;

CREATE VIEW agrovalle.v_precios_24h AS
SELECT pr.id_producto, pr.nombre,
       ROUND(AVG(v.precio_unitario_cop_kg), 2) AS promedio_cop_kg,
       COUNT(v.id_detalle) AS cantidad_transacciones
FROM agrovalle.producto pr
LEFT JOIN (
    SELECT c.id_producto, d.id_detalle, d.precio_unitario_cop_kg
    FROM agrovalle.detalle_pedido d
    JOIN agrovalle.reserva r ON r.id_reserva = d.id_reserva
    JOIN agrovalle.cosecha c ON c.id_cosecha = r.id_cosecha
    JOIN agrovalle.pedido p ON p.id_pedido = d.id_pedido
    WHERE p.estado = 'ENTREGADO'
      AND p.fecha_completado >= CURRENT_TIMESTAMP - INTERVAL '24 hours'
      AND p.fecha_completado <= CURRENT_TIMESTAMP
) v ON v.id_producto = pr.id_producto
GROUP BY pr.id_producto, pr.nombre;

