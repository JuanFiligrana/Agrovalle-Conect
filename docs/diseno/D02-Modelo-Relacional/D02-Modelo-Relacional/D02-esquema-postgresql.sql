BEGIN;
CREATE SCHEMA IF NOT EXISTS agrovalle;

CREATE TABLE agrovalle.municipio (
    id_municipio BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    CONSTRAINT pk_municipio PRIMARY KEY (id_municipio),
    CONSTRAINT uq_municipio_1 UNIQUE (nombre),
    CONSTRAINT ck_municipio_1 CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE agrovalle.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    contrasena_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_usuario PRIMARY KEY (id_usuario),
    CONSTRAINT ck_usuario_1 CHECK (length(btrim(nombre)) > 0),
    CONSTRAINT ck_usuario_2 CHECK (length(btrim(correo)) > 0),
    CONSTRAINT ck_usuario_3 CHECK (length(contrasena_hash) > 0)
);

CREATE TABLE agrovalle.agricultor (
    id_usuario BIGINT NOT NULL,
    cedula VARCHAR(20) NOT NULL,
    id_municipio BIGINT NOT NULL,
    CONSTRAINT pk_agricultor PRIMARY KEY (id_usuario),
    CONSTRAINT uq_agricultor_1 UNIQUE (cedula),
    CONSTRAINT fk_agricultor_id_usuario FOREIGN KEY (id_usuario) REFERENCES agrovalle.usuario (id_usuario) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_agricultor_id_municipio FOREIGN KEY (id_municipio) REFERENCES agrovalle.municipio (id_municipio) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_agricultor_1 CHECK (length(btrim(cedula)) > 0)
);

CREATE TABLE agrovalle.comprador (
    id_usuario BIGINT NOT NULL,
    CONSTRAINT pk_comprador PRIMARY KEY (id_usuario),
    CONSTRAINT fk_comprador_id_usuario FOREIGN KEY (id_usuario) REFERENCES agrovalle.usuario (id_usuario) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE agrovalle.finca (
    id_finca BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_agricultor BIGINT NOT NULL,
    id_municipio BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    CONSTRAINT pk_finca PRIMARY KEY (id_finca),
    CONSTRAINT fk_finca_id_agricultor FOREIGN KEY (id_agricultor) REFERENCES agrovalle.agricultor (id_usuario) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_finca_id_municipio FOREIGN KEY (id_municipio) REFERENCES agrovalle.municipio (id_municipio) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_finca_1 CHECK (length(btrim(nombre)) > 0),
    CONSTRAINT ck_finca_2 CHECK (length(btrim(direccion)) > 0)
);

CREATE TABLE agrovalle.categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    CONSTRAINT pk_categoria PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_1 UNIQUE (nombre),
    CONSTRAINT ck_categoria_1 CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE agrovalle.producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_categoria BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    CONSTRAINT pk_producto PRIMARY KEY (id_producto),
    CONSTRAINT uq_producto_1 UNIQUE (nombre),
    CONSTRAINT fk_producto_id_categoria FOREIGN KEY (id_categoria) REFERENCES agrovalle.categoria (id_categoria) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_producto_1 CHECK (length(btrim(nombre)) > 0)
);

CREATE TABLE agrovalle.cosecha (
    id_cosecha BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_finca BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,
    precio_cop_kg NUMERIC(14,2) NOT NULL,
    cantidad_fisica_kg NUMERIC(14,3) NOT NULL,
    fecha_cosecha DATE NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cosecha PRIMARY KEY (id_cosecha),
    CONSTRAINT fk_cosecha_id_finca FOREIGN KEY (id_finca) REFERENCES agrovalle.finca (id_finca) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_cosecha_id_producto FOREIGN KEY (id_producto) REFERENCES agrovalle.producto (id_producto) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_cosecha_1 CHECK (precio_cop_kg > 0),
    CONSTRAINT ck_cosecha_2 CHECK (cantidad_fisica_kg >= 0)
);

CREATE TABLE agrovalle.carrito (
    id_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_comprador BIGINT NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(12) NOT NULL DEFAULT 'ABIERTO',
    CONSTRAINT pk_carrito PRIMARY KEY (id_carrito),
    CONSTRAINT fk_carrito_id_comprador FOREIGN KEY (id_comprador) REFERENCES agrovalle.comprador (id_usuario) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_carrito_1 CHECK (estado IN ('ABIERTO','CERRADO'))
);

CREATE TABLE agrovalle.reserva (
    id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_carrito BIGINT NOT NULL,
    id_cosecha BIGINT NOT NULL,
    cantidad_kg NUMERIC(14,3) NOT NULL,
    precio_aceptado_cop_kg NUMERIC(14,2) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vence_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP + INTERVAL '15 minutes',
    estado VARCHAR(12) NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT pk_reserva PRIMARY KEY (id_reserva),
    CONSTRAINT fk_reserva_id_carrito FOREIGN KEY (id_carrito) REFERENCES agrovalle.carrito (id_carrito) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_reserva_id_cosecha FOREIGN KEY (id_cosecha) REFERENCES agrovalle.cosecha (id_cosecha) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_reserva_1 CHECK (cantidad_kg > 0),
    CONSTRAINT ck_reserva_2 CHECK (precio_aceptado_cop_kg > 0),
    CONSTRAINT ck_reserva_3 CHECK (vence_en = fecha_creacion + INTERVAL '15 minutes'),
    CONSTRAINT ck_reserva_4 CHECK (estado IN ('ACTIVA','CONSUMIDA','VENCIDA'))
);

CREATE TABLE agrovalle.pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_carrito BIGINT NOT NULL,
    id_agricultor BIGINT NOT NULL,
    fecha_confirmacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(24) NOT NULL DEFAULT 'PENDIENTE',
    fecha_completado TIMESTAMPTZ,
    CONSTRAINT pk_pedido PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedido_id_carrito FOREIGN KEY (id_carrito) REFERENCES agrovalle.carrito (id_carrito) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_id_agricultor FOREIGN KEY (id_agricultor) REFERENCES agrovalle.agricultor (id_usuario) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_pedido_1 CHECK (estado IN ('PENDIENTE','LISTO_PARA_DESPACHO','EN_CAMINO','ENTREGADO','CANCELADA')),
    CONSTRAINT ck_pedido_2 CHECK (((estado = 'ENTREGADO' AND fecha_completado IS NOT NULL) OR (estado <> 'ENTREGADO' AND fecha_completado IS NULL))),
    CONSTRAINT ck_pedido_3 CHECK (fecha_completado >= fecha_confirmacion)
);

CREATE TABLE agrovalle.detalle_pedido (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_pedido BIGINT NOT NULL,
    id_reserva BIGINT NOT NULL,
    cantidad_kg NUMERIC(14,3) NOT NULL,
    precio_unitario_cop_kg NUMERIC(14,2) NOT NULL,
    CONSTRAINT pk_detalle_pedido PRIMARY KEY (id_detalle),
    CONSTRAINT uq_detalle_pedido_1 UNIQUE (id_reserva),
    CONSTRAINT fk_detalle_pedido_id_pedido FOREIGN KEY (id_pedido) REFERENCES agrovalle.pedido (id_pedido) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_detalle_pedido_id_reserva FOREIGN KEY (id_reserva) REFERENCES agrovalle.reserva (id_reserva) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_detalle_pedido_1 CHECK (cantidad_kg > 0),
    CONSTRAINT ck_detalle_pedido_2 CHECK (precio_unitario_cop_kg > 0)
);

CREATE TABLE agrovalle.envio (
    id_envio BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_pedido BIGINT NOT NULL,
    fecha_programada TIMESTAMPTZ NOT NULL,
    ruta_descriptiva VARCHAR(500) NOT NULL,
    CONSTRAINT pk_envio PRIMARY KEY (id_envio),
    CONSTRAINT uq_envio_1 UNIQUE (id_pedido),
    CONSTRAINT fk_envio_id_pedido FOREIGN KEY (id_pedido) REFERENCES agrovalle.pedido (id_pedido) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_envio_1 CHECK (length(btrim(ruta_descriptiva)) > 0)
);

CREATE TABLE agrovalle.evento_seguimiento (
    id_evento BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_pedido BIGINT NOT NULL,
    estado VARCHAR(24) NOT NULL,
    fecha_evento TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    descripcion VARCHAR(500),
    CONSTRAINT pk_evento_seguimiento PRIMARY KEY (id_evento),
    CONSTRAINT fk_evento_seguimiento_id_pedido FOREIGN KEY (id_pedido) REFERENCES agrovalle.pedido (id_pedido) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_evento_seguimiento_1 CHECK (estado IN ('PENDIENTE','LISTO_PARA_DESPACHO','EN_CAMINO','ENTREGADO','CANCELADA'))
);

CREATE TABLE agrovalle.contacto (
    id_contacto BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_comprador BIGINT NOT NULL,
    id_cosecha BIGINT NOT NULL,
    mensaje VARCHAR(1000) NOT NULL,
    fecha_contacto TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(12) NOT NULL DEFAULT 'ENVIADO',
    CONSTRAINT pk_contacto PRIMARY KEY (id_contacto),
    CONSTRAINT fk_contacto_id_comprador FOREIGN KEY (id_comprador) REFERENCES agrovalle.comprador (id_usuario) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_contacto_id_cosecha FOREIGN KEY (id_cosecha) REFERENCES agrovalle.cosecha (id_cosecha) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_contacto_1 CHECK (length(btrim(mensaje)) > 0),
    CONSTRAINT ck_contacto_2 CHECK (estado IN ('ENVIADO','LEIDO','CONTESTADO'))
