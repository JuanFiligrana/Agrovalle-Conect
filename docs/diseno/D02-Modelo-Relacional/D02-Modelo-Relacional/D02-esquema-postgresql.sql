CREATE TABLE agrovalle.notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_destinatario BIGINT NOT NULL,
    id_contacto BIGINT,
    id_evento BIGINT,
    tipo VARCHAR(32) NOT NULL,
