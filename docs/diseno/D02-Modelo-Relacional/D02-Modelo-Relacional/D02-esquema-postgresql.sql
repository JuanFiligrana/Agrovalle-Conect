    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_notificacion PRIMARY KEY (id_notificacion),
    CONSTRAINT uq_notificacion_1 UNIQUE (id_contacto),
    CONSTRAINT fk_notificacion_id_destinatario FOREIGN KEY (id_destinatario) REFERENCES agrovalle.usuario (id_usuario) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_notificacion_id_contacto FOREIGN KEY (id_contacto) REFERENCES agrovalle.contacto (id_contacto) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_notificacion_id_evento FOREIGN KEY (id_evento) REFERENCES agrovalle.evento_seguimiento (id_evento) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_notificacion_1 CHECK (((id_contacto IS NOT NULL AND id_evento IS NULL) OR (id_contacto IS NULL AND id_evento IS NOT NULL))),
